export const useI18nStore = defineStore('i18n', () => {
  const locale = ref<Language>(
    (localStorage.getItem('language') as Language) || 'pt'
  )

  const setLocale = (lang: Language) => {
    locale.value = lang
    localStorage.setItem('language', lang)
  }

  return {
    locale,
    translations,
    setLocale,
  }
})
